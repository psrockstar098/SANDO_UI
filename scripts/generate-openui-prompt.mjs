/**
 * Generates the OpenUI system prompt and writes it as a Zig source file.
 *
 * The Zig backend appends this specification to Sando's existing system
 * prompt when a request asks for `mode: "ui"`. Keeping it in the backend
 * means the browser never controls the system prompt and Next does not
 * regenerate it on every request.
 *
 * Usage:
 *   node scripts/generate-openui-prompt.mjs [outPath]
 */

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { generateSystemPrompt } from "@openuidev/react-lang";
import {
  openuiLibrary,
  openuiPromptOptions,
} from "@openuidev/react-ui/genui-lib";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const defaultOut = resolve(root, "../../sando/src/connnector/openui_spec.zig");
const out = resolve(process.cwd(), process.argv[2] ?? defaultOut);

const prompt = generateSystemPrompt({
  library: openuiLibrary,
  promptOptions: openuiPromptOptions,
});

if (prompt.length <= 20_000) {
  console.error(`OpenUI prompt is unexpectedly short (${prompt.length} chars).`);
  process.exit(1);
}
if (!prompt.includes("openui-lang")) {
  console.error("OpenUI prompt does not mention openui-lang.");
  process.exit(1);
}

// Zig multiline string literals have no escape processing: the content is
// everything after the leading `\\` token on each line. Indent for the
// source, but do not double backslashes or it would change the prompt.
const body = prompt
  .split("\n")
  .map((line) => `    \\\\${line}`)
  .join("\n");

const source = `// Generated by sando_ui/scripts/generate-openui-prompt.mjs. Do not edit by hand.
pub const spec =
${body}
;
`;

writeFileSync(out, source);
console.log(`wrote ${out} (${prompt.length} chars)`);
