/**
 * Generates `app/openui-monochrome.css` from the OpenUI stylesheet.
 *
 * Every OpenUI color token is an `oklch()` value. The design rule is
 * black/white only, so each token keeps its lightness and alpha but loses
 * all chroma. Shadows can contain several `oklch()` values, so the rewrite
 * is done per occurrence, not per token.
 *
 * Only declarations from the theme blocks are collected. Component-scoped
 * overrides (for example a chip that redefines `--openui-background`) must
 * not leak into `:root`.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const source = resolve(
  root,
  "node_modules/@openuidev/react-ui/dist/styles/index.css",
);
const target = resolve(root, "app/openui-monochrome.css");

const THEME_SELECTORS = new Set([
  ":root",
  ":root:not([data-openui-theme=light])",
  ':root[data-openui-theme="dark"]',
  ":root[data-openui-theme=dark]",
]);

const css = readFileSync(source, "utf8");

/** Walks the stylesheet and collects theme-block custom properties. */
function collectThemeTokens(input) {
  const tokens = new Map();
  const stack = [];
  let buffer = "";
  let i = 0;

  const flushDeclaration = () => {
    const text = buffer.trim();
    buffer = "";
    if (!text.startsWith("--openui-")) return;

    const selector = stack[stack.length - 1];
    if (!THEME_SELECTORS.has(selector)) return;

    // Accept only top-level theme blocks or theme blocks inside @media.
    const ancestors = stack.slice(0, -1);
    if (!ancestors.every((entry) => entry.startsWith("@media"))) return;

    const colon = text.indexOf(":");
    if (colon === -1) return;
    const name = text.slice(0, colon).trim();
    const value = text.slice(colon + 1).trim();
    if (!value.includes("oklch(")) return;

    // Later declarations win: the dark theme is emitted after the light one.
    tokens.set(name, value);
  };

  while (i < input.length) {
    const char = input[i];

    if (char === "{") {
      stack.push(buffer.trim());
      buffer = "";
      i += 1;
      continue;
    }

    if (char === "}") {
      flushDeclaration();
      stack.pop();
      buffer = "";
      i += 1;
      continue;
    }

    if (char === ";" && stack.length > 0) {
      flushDeclaration();
      i += 1;
      continue;
    }

    buffer += char;
    i += 1;
  }

  return tokens;
}

/** Replaces the chroma component of every oklch() in a value with 0. */
function neutralize(value) {
  return value.replace(/oklch\(([^)]*)\)/g, (match, body) => {
    const parts = body.trim().split(/\s+/);
    if (parts.length < 3) {
      console.error(`UNSUPPORTED oklch(${body})`);
      process.exitCode = 1;
      return match;
    }
    const [l, c, ...rest] = parts;
    if (Number.isNaN(Number(l)) || Number.isNaN(Number(c))) {
      console.error(`UNSUPPORTED oklch(${body})`);
      process.exitCode = 1;
      return match;
    }
    return `oklch(${l} 0 ${rest.join(" ")})`;
  });
}

const tokens = collectThemeTokens(css);
if (tokens.size === 0) {
  console.error("No OpenUI theme tokens found in", source);
  process.exit(1);
}

const lines = [...tokens.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, value]) => `  ${name}: ${neutralize(value)};`);

const output = `/* Generated by scripts/generate-openui-theme.mjs. Do not edit by hand. */
:root,
:root:not([data-openui-theme="light"]),
:root[data-openui-theme="dark"] {
${lines.join("\n")}
}
`;

writeFileSync(target, output);
console.log(`wrote app/openui-monochrome.css (${tokens.size} tokens)`);

if (process.exitCode) {
  console.error("Some oklch() values could not be parsed.");
}
